package us.to.midensthings.nouveauEnchanting.datapack;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import io.papermc.paper.datapack.Datapack;
import io.papermc.paper.plugin.bootstrap.BootstrapContext;
import io.papermc.paper.plugin.lifecycle.event.types.LifecycleEvents;
import net.kyori.adventure.text.Component;
import net.kyori.adventure.text.logger.slf4j.ComponentLogger;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.stream.Stream;

/***
 * The datapack NouveauEnchanting generates for enchantment effects. It's written from scratch on every start, so
 * settings that were removed don't leave old files behind, then loaded on top of vanilla so its files replace vanilla's.
 */
public final class GeneratedDatapack {
    /** The pack's ID, it shows up in /datapack list as NouveauEnchanting/generated. */
    public static final String PACK_ID = "generated";

    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create();

    private final Path folder;
    private final ComponentLogger logger;
    // Path inside the pack (e.g. data/minecraft/enchantment/sharpness.json) -> its contents
    private final Map<String, JsonElement> files = new LinkedHashMap<>();
    private boolean written = false;

    public GeneratedDatapack(Path folder, ComponentLogger logger) {
        this.folder = folder;
        this.logger = logger;
    }

    /***
     * Adds a file to the pack, replacing any file already added at that path.
     * @param path the path inside the pack, e.g. data/minecraft/enchantment/sharpness.json
     */
    public void addFile(String path, JsonElement json) {
        files.put(path, json);
    }

    /***
     * Adds an enchantment definition to the pack.
     */
    public void addEnchantment(String namespace, String id, JsonObject definition) {
        addFile("data/" + namespace + "/enchantment/" + id + ".json", definition);
    }

    public boolean isEmpty() {
        return files.isEmpty();
    }

    /***
     * Deletes the old pack and writes the new one. Nothing is written if the pack is empty.
     * @param dataPackFormat the server's data pack format as {major, minor}, only needed if the pack isn't empty
     * @return true if the pack was written and should be loaded.
     */
    public boolean write(int[] dataPackFormat) {
        try {
            deleteFolder();
            if (files.isEmpty() || dataPackFormat == null) {
                return false;
            }

            Files.createDirectories(folder);
            writeJson(folder.resolve("pack.mcmeta"), createPackMeta(dataPackFormat));
            for (Map.Entry<String, JsonElement> file : files.entrySet()) {
                Path path = folder.resolve(file.getKey());
                Files.createDirectories(path.getParent());
                writeJson(path, file.getValue());
            }
            written = true;
            logger.info("Generated a datapack with " + files.size() + " file(s)");
            return true;
        } catch (IOException e) {
            logger.error("Could not write the generated datapack to " + folder, e);
            return false;
        }
    }

    /***
     * Tells the server to load the pack, above vanilla so its files replace vanilla's. Does nothing if the pack wasn't written.
     */
    public void register(BootstrapContext context) {
        if (!written) {
            return;
        }
        context.getLifecycleManager().registerEventHandler(LifecycleEvents.DATAPACK_DISCOVERY, event -> {
            try {
                event.registrar().discoverPack(folder, PACK_ID, configurer -> configurer
                        .title(Component.text("Nouveau Enchanting"))
                        .autoEnableOnServerStart(true)
                        .position(false, Datapack.Position.TOP));
            } catch (IOException e) {
                logger.error("Could not load the generated datapack from " + folder, e);
            }
        });
    }

    private JsonObject createPackMeta(int[] dataPackFormat) {
        // Only for this server's exact data pack format, the pack is generated again for the next version anyway
        JsonArray format = new JsonArray();
        format.add(dataPackFormat[0]);
        format.add(dataPackFormat[1]);

        JsonObject pack = new JsonObject();
        pack.addProperty("description", "Enchantment effects generated by Nouveau Enchanting. Changes here are overwritten on every start.");
        pack.add("min_format", format);
        pack.add("max_format", format);

        JsonObject meta = new JsonObject();
        meta.add("pack", pack);
        return meta;
    }

    private void writeJson(Path path, JsonElement json) throws IOException {
        Files.writeString(path, GSON.toJson(json), StandardCharsets.UTF_8);
    }

    private void deleteFolder() throws IOException {
        if (!Files.exists(folder)) {
            return;
        }
        try (Stream<Path> paths = Files.walk(folder)) {
            // Deepest first, so folders are empty when they're deleted
            for (Path path : paths.sorted(Comparator.reverseOrder()).toList()) {
                Files.delete(path);
            }
        }
    }
}
